    bind(IngotWorkspaceFileService).toSelf().inSingletonScope();
    rebind(WorkspaceFileService).toService(IngotWorkspaceFileService);
    bind(IngotGroupService).toSelf().inSingletonScope();
    bind(IngotProjectTabsWidget).toSelf().inSingletonScope();
    bind(IngotGroupsContribution).toSelf().inSingletonScope();
    for (const id of [FrontendApplicationContribution, CommandContribution, KeybindingContribution]) {
        bind(id).toService(IngotGroupsContribution);
    }
    bindModelPreferences(bind);
    bind(PreferenceContribution).toConstantValue({ schema: keymapPreferenceSchema });
    bind(PreferenceContribution).toConstantValue({ schema: appearancePreferenceSchema });
    bind(PreferenceContribution).toConstantValue({ schema: layoutPreferenceSchema });
    bind(IngotLayoutContribution).toSelf().inSingletonScope();
    bind(CommandContribution).toService(IngotLayoutContribution);
    bind(MenuContribution).toService(IngotLayoutContribution);
    bind(AppearanceContribution).toSelf().inSingletonScope();
    bind(FrontendApplicationContribution).toService(AppearanceContribution);
    bind(CommandContribution).toService(AppearanceContribution);
    bind(NavigationHistory).toSelf().inSingletonScope();
    bind(ProjectConfigService).toSelf().inSingletonScope();
    bind(GitService).toDynamicValue(ctx => ServiceConnectionProvider.createProxy<GitService>(ctx.container, GIT_SERVICE_PATH)).inSingletonScope();
    bind(GitResourceResolver).toSelf().inSingletonScope();
    bind(ResourceResolver).toService(GitResourceResolver);
    bind(IngotGitLogWidget).toSelf();
    bind(WidgetFactory).toDynamicValue(ctx => ({ id: GIT_LOG_WIDGET_ID, createWidget: () => ctx.container.get(IngotGitLogWidget) })).inSingletonScope();
    bindViewContribution(bind, IngotGitContribution);
    bind(IngotGitActionsContribution).toSelf().inSingletonScope();
    for (const id of [CommandContribution, MenuContribution, KeybindingContribution]) {
        bind(id).toService(IngotGitActionsContribution);
    }
    // IDEA-74: Local Changes / Commit tool window, diff viewer, Push dialog
    bind(LocalChangesModel).toSelf().inSingletonScope();
    bind(LocalChangesWidget).toSelf();
    bind(WidgetFactory).toDynamicValue(ctx => ({ id: LOCAL_CHANGES_WIDGET_ID, createWidget: () => ctx.container.get(LocalChangesWidget) })).inSingletonScope();
    bind(IngotDiffWidget).toSelf();
    bind(WidgetFactory).toDynamicValue(ctx => createDiffWidgetFactory(options => {
        const widget = ctx.container.get(IngotDiffWidget);
        widget.init(options);
        return widget;
    })).inSingletonScope();
    bindViewContribution(bind, IngotCommitContribution);
    bind(IngotMergeWidget).toSelf();
    bind(WidgetFactory).toDynamicValue(ctx => createMergeWidgetFactory(options => {
        const widget = ctx.container.get(IngotMergeWidget);
        widget.init(options);
        return widget;
    })).inSingletonScope();
    // IDEA-76: breadcrumbs bar (root › folders › file › symbol chain), outline tree popup and info hovers.
    bind(BreadcrumbHover).toSelf().inSingletonScope();
    bind(IngotBreadcrumbRenderer).toSelf().inSingletonScope();
    rebind(BreadcrumbsRendererFactory).toFactory(ctx => () => {
        const child = ctx.container.createChild();
        child.bind(BreadcrumbRenderer).toDynamicValue(() => ctx.container.get(IngotBreadcrumbRenderer)).inSingletonScope();
        return child.get(BreadcrumbsRenderer);
    });
    rebind(FilepathBreadcrumbsContribution).to(IngotWorkspaceBreadcrumbs).inSingletonScope();
    rebind(OutlineBreadcrumbsContribution).to(IngotOutlineBreadcrumbs).inSingletonScope();
    bind(IngotAnnotateContribution).toSelf().inSingletonScope();
    bind(FrontendApplicationContribution).toService(IngotAnnotateContribution);
    bind(CommandContribution).toService(IngotAnnotateContribution);
    bind(MenuContribution).toService(IngotAnnotateContribution);
    bind(IngotMergeContribution).toSelf().inSingletonScope();
    bind(CommandContribution).toService(IngotMergeContribution);
    bind(KeybindingContribution).toService(IngotMergeContribution);
    bind(IngotFileMenusContribution).toSelf().inSingletonScope();
    for (const id of [CommandContribution, MenuContribution, KeybindingContribution, FrontendApplicationContribution]) {
        bind(id).toService(IngotFileMenusContribution);
    }
    bind(McpService).toDynamicValue(ctx => ServiceConnectionProvider.createProxy<McpService>(ctx.container, MCP_SERVICE_PATH)).inSingletonScope();
    bind(IngotMcpClient).toSelf().inSingletonScope();
    bind(IngotAgentConfigWidget).toSelf();
    bind(WidgetFactory).toDynamicValue(ctx => ({ id: AGENT_CONFIG_WIDGET_ID, createWidget: () => ctx.container.get(IngotAgentConfigWidget) })).inSingletonScope();
    bindViewContribution(bind, IngotAgentConfigContribution);
    bind(FrontendApplicationContribution).toService(IngotAgentConfigContribution);
    bind(IngotKeymapContribution).toSelf().inSingletonScope();
    bind(FrontendApplicationContribution).toService(IngotKeymapContribution);
    bind(CommandContribution).toService(IngotKeymapContribution);
    bind(IngotRunContribution).toSelf().inSingletonScope();
    bind(CommandContribution).toService(IngotRunContribution);
    bind(ModelService).toDynamicValue(ctx => ServiceConnectionProvider.createProxy<ModelService>(ctx.container, MODEL_SERVICE_PATH)).inSingletonScope();
    bind(IngotModelClient).toSelf().inSingletonScope();
    bind(IngotInlineCompletions).toSelf().inSingletonScope();
    bind(IngotModelsWidget).toSelf();
    bind(WidgetFactory).toDynamicValue(ctx => ({ id: MODELS_WIDGET_ID, createWidget: () => ctx.container.get(IngotModelsWidget) })).inSingletonScope();
    bindViewContribution(bind, IngotModelsContribution);
    bind(FrontendApplicationContribution).toService(IngotModelsContribution);
    bind(GroupChannel).toSelf().inSingletonScope();
    bind(IngotGroupChatWidget).toSelf();
    bind(WidgetFactory).toDynamicValue(ctx => ({ id: GROUP_CHAT_WIDGET_ID, createWidget: () => ctx.container.get(IngotGroupChatWidget) })).inSingletonScope();
    bindViewContribution(bind, IngotGroupChatContribution);
    bind(FrontendApplicationContribution).toService(IngotGroupChatContribution);
    bind(IngotCoreContribution).toSelf().inSingletonScope();
    bind(CommandContribution).toService(IngotCoreContribution);
    bind(MenuContribution).toService(IngotCoreContribution);

    bind(IngotThemeContribution).toSelf().inSingletonScope();
    bind(FrontendApplicationContribution).toService(IngotThemeContribution);

    bind(IngotMainToolbar).toSelf().inSingletonScope();
    bind(IngotShellContribution).toSelf().inSingletonScope();
    bind(FrontendApplicationContribution).toService(IngotShellContribution);
    bind(CommandContribution).toService(IngotShellContribution);
    bind(KeybindingContribution).toService(IngotShellContribution);

    bind(IngotWelcomeWidget).toSelf();
    bind(WidgetFactory).toDynamicValue(ctx => ({ id: WELCOME_WIDGET_ID, createWidget: () => ctx.container.get(IngotWelcomeWidget) })).inSingletonScope();
    bindViewContribution(bind, IngotWelcomeContribution);
    bind(FrontendApplicationContribution).toService(IngotWelcomeContribution);

    bind(PortsService).toDynamicValue(ctx => ServiceConnectionProvider.createProxy<PortsService>(ctx.container, PORTS_SERVICE_PATH)).inSingletonScope();
    bind(IngotPortsWidget).toSelf();
    bind(WidgetFactory).toDynamicValue(ctx => ({ id: PORTS_WIDGET_ID, createWidget: () => ctx.container.get(IngotPortsWidget) })).inSingletonScope();
    bindViewContribution(bind, IngotPortsContribution);

    bind(AgentStore).toSelf().inSingletonScope();
    bind(MemoryStore).toSelf().inSingletonScope();
    bind(AgentEditReview).toSelf().inSingletonScope();
    bind(EditorCopyTracker).toSelf().inSingletonScope();
    bind(FrontendApplicationContribution).toService(EditorCopyTracker);
    bind(IngotAgentsWidget).toSelf();
    bind(WidgetFactory).toDynamicValue(ctx => ({ id: AGENTS_WIDGET_ID, createWidget: () => ctx.container.get(IngotAgentsWidget) })).inSingletonScope();
    bindViewContribution(bind, IngotAgentsContribution);

    bind(IngotAccountService).toSelf().inSingletonScope();
    bind(IngotAccountContribution).toSelf().inSingletonScope();
    for (const id of [CommandContribution, MenuContribution, FrontendApplicationContribution]) {
        bind(id).toService(IngotAccountContribution);
    }
    bind(IngotExplorerHeader).toSelf().inSingletonScope();
    bind(IngotStripeWidget).toSelf().inSingletonScope();
    bind(IngotRightStripeWidget).toSelf().inSingletonScope();
    bind(IngotDatabaseWidget).toSelf();
    bind(IngotMcpWidget).toSelf();
    bind(IngotServicesWidget).toSelf();
    bind(WidgetFactory).toDynamicValue(ctx => ({ id: DATABASE_WIDGET_ID, createWidget: () => ctx.container.get(IngotDatabaseWidget) })).inSingletonScope();
    bind(WidgetFactory).toDynamicValue(ctx => ({ id: MCP_WIDGET_ID, createWidget: () => ctx.container.get(IngotMcpWidget) })).inSingletonScope();
    bind(WidgetFactory).toDynamicValue(ctx => ({ id: SERVICES_WIDGET_ID, createWidget: () => ctx.container.get(IngotServicesWidget) })).inSingletonScope();
    bindViewContribution(bind, IngotDatabaseContribution);
    bindViewContribution(bind, IngotMcpContribution);
    bindViewContribution(bind, IngotServicesContribution);
    bind(IngotBranchService).toSelf().inSingletonScope();
    bind(IngotStatusBarContribution).toSelf().inSingletonScope();
    bind(FrontendApplicationContribution).toService(IngotStatusBarContribution);

    bind(IngotEditorContribution).toSelf().inSingletonScope();
    rebind(EditorContribution).toService(IngotEditorContribution);

    bind(IngotAboutDialog).toSelf().inSingletonScope();
    rebind(AboutDialog).toService(IngotAboutDialog);

    bind(SettingsDialogProps).toConstantValue({ title: 'Settings' });
    bind(IngotSettingsDialog).toSelf().inSingletonScope();
    bind(SettingsDialogProvider).toProvider(ctx => () => ctx.container.getAsync(IngotSettingsDialog));
    bind(IngotSettingsContribution).toSelf().inSingletonScope();
    bind(CommandContribution).toService(IngotSettingsContribution);
    bind(MenuContribution).toService(IngotSettingsContribution);
    bind(FrontendApplicationContribution).toService(IngotSettingsContribution);

    bind(UserThemeContribution).toSelf().inSingletonScope();
    bind(FrontendApplicationContribution).toService(UserThemeContribution);
    bind(CommandContribution).toService(UserThemeContribution);
    bind(IngotIconTheme).toSelf().inSingletonScope();
    bind(IconThemeContribution).toService(IngotIconTheme);
    bind(LabelProviderContribution).toService(IngotIconTheme);
    bind(IngotEditorContextMenuContribution).toSelf().inSingletonScope();
    bind(CommandContribution).toService(IngotEditorContextMenuContribution);
    bind(MenuContribution).toService(IngotEditorContextMenuContribution);
    bind(FrontendApplicationContribution).toService(IngotEditorContextMenuContribution);
