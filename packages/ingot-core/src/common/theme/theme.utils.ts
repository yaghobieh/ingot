export const buildTokenColors = ({ syntax: s }: IngotThemeDefinition): TokenColorRule[] => [
    rule(['comment', 'punctuation.definition.comment'], s.comment, 'italic'),
    rule(['keyword', 'storage', 'storage.type', 'storage.modifier', 'keyword.control', 'keyword.operator.new'], s.keyword),
    rule(['string', 'string.quoted', 'string.template'], s.string),
    rule(['constant.numeric'], s.number),
    rule(['constant.language', 'constant.other', 'variable.other.constant'], s.constant),
    rule(['entity.name.function', 'support.function', 'meta.function-call'], s.function),
    rule(['entity.name.type', 'entity.name.class', 'support.type', 'support.class', 'entity.other.inherited-class'], s.type),
    rule(['variable.other.property', 'variable.other.object.property', 'support.variable.property', 'meta.object-literal.key'], s.property),
    rule(['variable', 'variable.parameter'], s.variable),
    rule(['entity.name.tag'], s.tag),
    rule(['entity.other.attribute-name'], s.attribute)
];

export const buildThemeJson = (theme: IngotThemeDefinition): VsCodeThemeJson => ({
    name: theme.label,
    type: theme.uiTheme === 'vs' ? 'light' : 'dark',
    colors: buildWorkbenchColors(theme),
    tokenColors: buildTokenColors(theme)
});
