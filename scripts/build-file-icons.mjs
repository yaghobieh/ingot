#!/usr/bin/env node
// IDEA-106: Ingot Files icon theme.
//   node scripts/build-file-icons.mjs --vendor <material-icon-theme>/icons   copies the icons the map uses into assets/file-icons
//   node scripts/build-file-icons.mjs                                       writes packages/ingot-core/src/browser/style/file-icons.css
// Icons: Material Icon Theme by Material Extensions, MIT (assets/file-icons/LICENSE). Run `npm run build:packages` first (reads the map from lib).
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createRequire } from 'node:module';

const DIR = 'assets/file-icons';
const OUT = 'packages/ingot-core/src/browser/style/file-icons.css';
const require = createRequire(import.meta.url);
const { ALL_FILE_ICONS } = require('../packages/ingot-core/lib/common/icons/file-icon-map.js');

const vendorAt = process.argv.indexOf('--vendor');
if (vendorAt > 0) {
    const from = process.argv[vendorAt + 1];
    mkdirSync(DIR, { recursive: true });
    const missing = [];
    for (const name of ALL_FILE_ICONS) {
        const src = join(from, `${name}.svg`);
        existsSync(src) ? copyFileSync(src, join(DIR, `${name}.svg`)) : missing.push(name);
    }
    copyFileSync(join(from, '..', 'LICENSE'), join(DIR, 'LICENSE'));
    if (missing.length) {
        console.error(`file-icons: not in the source set: ${missing.join(', ')}`);
        process.exit(1);
    }
}

const toDataUri = svg => `url("data:image/svg+xml;utf8,${encodeURIComponent(svg.trim().replace(/\s+/g, ' '))}")`;
const files = readdirSync(DIR).filter(f => f.endsWith('.svg')).sort();
const lost = ALL_FILE_ICONS.filter(n => !files.includes(`${n}.svg`));
if (lost.length) {
    console.error(`file-icons: missing in ${DIR}: ${lost.join(', ')} (run with --vendor)`);
    process.exit(1);
}
let css = '/* Generated by scripts/build-file-icons.mjs — do not edit by hand. Icons: Material Icon Theme (MIT), see assets/file-icons/LICENSE. */\n';
css += '.ingot-ficon { display: inline-block; width: 16px; height: 16px; min-width: 16px; flex: none; vertical-align: text-bottom; background-image: var(--ingot-ficon) !important; background-position: center !important; background-size: 16px 16px !important; background-repeat: no-repeat !important; background-color: transparent !important; }\n';
css += '.ingot-ficon::before { content: none !important; }\n';
// Tree rows and editor tabs: a little room between the icon and the name.
css += '.theia-TreeNode .ingot-ficon { margin-right: 6px; }\n';
css += '.lm-TabBar-tab .lm-TabBar-tabIcon.ingot-ficon { width: 16px !important; height: 16px !important; margin-right: 6px; align-self: center; }\n';
for (const file of files) {
    const name = file.replace(/\.svg$/, '');
    css += `.ingot-ficon-${name.replace(/_/g, '-')} { --ingot-ficon: ${toDataUri(readFileSync(join(DIR, file), 'utf8'))}; }\n`;
}
writeFileSync(OUT, css);
console.log(`file-icons: ${files.length} icons -> ${OUT}`);
