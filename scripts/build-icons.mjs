#!/usr/bin/env node
// Generates packages/ingot-core/src/browser/style/icons.css from assets/icons/*.svg.
// Icons are used as CSS masks so they inherit `currentColor` in every theme.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ICON_DIR = 'assets/icons';
const OUT = 'packages/ingot-core/src/browser/style/icons.css';

const toDataUri = svg => `url("data:image/svg+xml;utf8,${encodeURIComponent(svg.trim())}")`;
const icons = readdirSync(ICON_DIR).filter(f => f.endsWith('.svg')).sort();
let css = '/* Generated by scripts/build-icons.mjs — do not edit by hand. */\n';
css += '.ingot-icon { display: inline-block; width: 16px; height: 16px; background-color: currentColor; -webkit-mask: var(--ingot-icon) center / contain no-repeat; mask: var(--ingot-icon) center / contain no-repeat; flex: none; }\n';
css += ':root {\n';
for (const file of icons) {
    css += `  --ingot-icon-${file.replace(/\.svg$/, '')}: ${toDataUri(readFileSync(join(ICON_DIR, file), 'utf8'))};\n`;
}
css += '}\n';
for (const file of icons) {
    const name = file.replace(/\.svg$/, '');
    css += `.ingot-icon-${name} { --ingot-icon: var(--ingot-icon-${name}); }\n`;
}
// Full-colour brand mark used by the toolbar, welcome screen and About dialog.
css += `.ingot-brand-mark { background: ${toDataUri(readFileSync('assets/brand/mark.svg', 'utf8'))} center / contain no-repeat; }\n`;
writeFileSync(OUT, css);
console.log(`icons: wrote ${icons.length} icons to ${OUT}`);
